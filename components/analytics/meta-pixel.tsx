import Script from "next/script";

/**
 * Meta Pixel de la cuenta de ads de Capital Inteligente — el mismo pixel que
 * usan hclp y encuentrosmart. Se monta SOLO en /liderazgo (ver
 * app/liderazgo/page.tsx): es la única página pública pensada para campañas
 * pagadas. Deliberadamente NO va en el layout global para no rastrear el
 * aula de los alumnos.
 *
 * Sin NEXT_PUBLIC_META_PIXEL_ID no renderiza nada: un despliegue sin la
 * variable sigue funcionando, solo sin pixel.
 */
export function MetaPixel() {
  const pixelId = process.env.NEXT_PUBLIC_META_PIXEL_ID;
  if (!pixelId) return null;

  return (
    <>
      <Script id="meta-pixel" strategy="afterInteractive">
        {`
          !function(f,b,e,v,n,t,s)
          {if(f.fbq)return;n=f.fbq=function(){n.callMethod?
          n.callMethod.apply(n,arguments):n.queue.push(arguments)};
          if(!f._fbq)f._fbq=n;n.push=n;n.loaded=!0;n.version='2.0';
          n.queue=[];t=b.createElement(e);t.async=!0;
          t.src=v;s=b.getElementsByTagName(e)[0];
          s.parentNode.insertBefore(t,s)}(window, document,'script',
          'https://connect.facebook.net/en_US/fbevents.js');
          fbq('init', '${pixelId}');
          fbq('track', 'PageView');
        `}
      </Script>
      <noscript>
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          height="1"
          width="1"
          alt=""
          style={{ display: "none" }}
          src={`https://www.facebook.com/tr?id=${pixelId}&ev=PageView&noscript=1`}
        />
      </noscript>
    </>
  );
}
